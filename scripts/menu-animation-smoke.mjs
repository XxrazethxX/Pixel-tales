import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(process.env.GAME_URL || "http://127.0.0.1:3002/");
  const scene = page.locator("#menu-scene");
  const waitPlaying = () => page.waitForFunction(() => {
    const v = document.querySelector("#menu-scene");
    return v.dataset.animating === "true" && !v.paused && v.readyState >= 2;
  });
  await waitPlaying();
  assert.equal(await scene.evaluate(v => v.videoWidth), 1280);
  assert.equal(await scene.evaluate(v => v.videoHeight), 720);
  assert.equal(await scene.evaluate(v => v.loop && v.muted && v.playsInline), true);
  assert.equal(await page.locator("#menu-effects").count(), 0, "Old overlays must be removed");
  const time = await scene.evaluate(v => v.currentTime);
  await page.waitForTimeout(250);
  assert.ok(await scene.evaluate(v => v.currentTime) > time);
  assert.equal(await scene.evaluate(v => getComputedStyle(v).pointerEvents), "none");
  await page.screenshot({ path: "docs/screenshots/main-menu-animated.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await scene.evaluate(v => getComputedStyle(v).objectPosition), "62% 50%");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Reduced motion", { exact: true }).check();
  assert.equal(await scene.evaluate(v => v.paused && v.hidden), true);
  const reducedTime = await scene.evaluate(v => v.currentTime);
  await page.waitForTimeout(200);
  assert.equal(await scene.evaluate(v => v.currentTime), reducedTime);
  await page.getByLabel("Reduced motion", { exact: true }).uncheck();
  await waitPlaying();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForTimeout(100);
  assert.equal(await scene.evaluate(v => v.paused && v.hidden), true);
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await waitPlaying();
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByRole("button", { name: "New Company", exact: true }).click();
  await page.getByRole("button", { name: "Begin adventure", exact: true }).click();
  assert.equal(await scene.evaluate(v => v.paused && v.hidden), true);
  await page.getByRole("button", { name: "Main menu", exact: true }).click();
  await waitPlaying();
  // Failure to load media retains a usable static title screen.
  const fallback = await browser.newPage();
  await fallback.route("**/main-menu-loop.mp4", route => route.abort());
  await fallback.goto(process.env.GAME_URL || "http://127.0.0.1:3002/");
  await fallback.waitForFunction(() => document.querySelector("#menu-scene").error);
  assert.equal(await fallback.locator("#menu-scene").isVisible(), false);
  await fallback.getByRole("button", { name: "New Company", exact: true }).click();
  await fallback.getByRole("button", { name: "Begin adventure", exact: true }).waitFor();
  // Motion preference is respected before video is fetched, not just afterwards.
  const reduced = await browser.newPage({ reducedMotion: "reduce" });
  await reduced.goto(process.env.GAME_URL || "http://127.0.0.1:3002/");
  assert.equal(await reduced.locator("#menu-scene").getAttribute("src"), null);
  assert.deepEqual(errors, []);
  console.log("PASS: complete looping video, mobile crop, input passthrough, reduced motion before/after playback, paused gameplay, restart and static media-failure fallback; no browser errors.");
} finally { await browser.close(); }
