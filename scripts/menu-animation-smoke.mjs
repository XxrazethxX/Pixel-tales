import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(process.env.GAME_URL || "http://127.0.0.1:3002/");
  const effect = page.locator("#menu-effects");
  await effect.waitFor();
  await page.waitForFunction(() => document.querySelector("#menu-effects").dataset.scale);
  assert.equal(await effect.getAttribute("data-animating"), "true");
  assert.equal(await effect.getAttribute("data-offset-x"), "0.00");
  const snapshot = () => effect.evaluate(c => c.toDataURL());
  const initial = await snapshot();
  await page.waitForTimeout(240);
  assert.notEqual(await snapshot(), initial, "Effects must change between frames");
  assert.equal(await effect.evaluate(c => getComputedStyle(c).pointerEvents), "none");
  await page.screenshot({ path: "docs/screenshots/main-menu-animated.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(150);
  const scale = Math.max(390 / 1672, 844 / 941);
  assert.ok(Math.abs(Number(await effect.getAttribute("data-offset-x")) - (390 - 1672 * scale) * .62) < .02);
  assert.ok(Math.abs(Number(await effect.getAttribute("data-offset-y"))) < .02);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Reduced motion", { exact: true }).check();
  assert.equal(await effect.getAttribute("data-animating"), "false");
  assert.equal(await effect.isVisible(), false);
  const reduced = await snapshot();
  await page.waitForTimeout(200);
  assert.equal(await snapshot(), reduced);
  await page.getByLabel("Reduced motion", { exact: true }).uncheck();
  assert.equal(await effect.getAttribute("data-animating"), "true");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForTimeout(100);
  assert.equal(await effect.isVisible(), false);
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.waitForTimeout(100);
  assert.equal(await effect.isVisible(), true);
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByRole("button", { name: "New Company", exact: true }).click();
  await page.getByRole("button", { name: "Begin adventure", exact: true }).click();
  assert.equal(await effect.getAttribute("data-animating"), "false");
  const playing = await snapshot();
  await page.waitForTimeout(200);
  assert.equal(await snapshot(), playing, "Hidden menu must not keep drawing");
  await page.getByRole("button", { name: "Main menu", exact: true }).click();
  assert.equal(await effect.getAttribute("data-animating"), "true");
  assert.deepEqual(errors, []);
  console.log("PASS: animated frames, desktop/mobile backdrop alignment, input passthrough, app and system reduced motion, paused gameplay and restart; no browser errors.");
} finally { await browser.close(); }
