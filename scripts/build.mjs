import { readFileSync, writeFileSync } from "node:fs";
import { Script } from "node:vm";
const engine = readFileSync(
  new URL("../src/game.js", import.meta.url),
  "utf8",
).replace(/^export /gm, "");
const artData = readFileSync(
  new URL("../src/art-assets.js", import.meta.url),
  "utf8",
).replace(/^export /gm, "");
const artwork = readFileSync(new URL("../src/art.js", import.meta.url), "utf8")
  .replace(/^export /gm, "")
  .replace(/^import [\s\S]*?;\n/gm, "");
const app = readFileSync(
  new URL("../src/app.js", import.meta.url),
  "utf8",
).replace(/^import [\s\S]*?;\n/gm, "");
const bundle =
  "// Generated by npm run build. Edit src/ files.\n(()=>{\n" +
  engine +
  "\n" +
  artData +
  "\n" +
  artwork +
  "\n" +
  app +
  "\n})();\n";
new Script(bundle);
writeFileSync(new URL("../game.bundle.js", import.meta.url), bundle);
console.log("Built offline browser game");
